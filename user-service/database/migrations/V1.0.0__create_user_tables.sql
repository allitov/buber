create table if not exists passenger
(
    id            bigint primary key generated by default as identity,
    name          varchar(255) not null,
    email         varchar(255),
    phone         varchar(20)  not null unique,
    registered_at timestamptz  not null default now()
);
comment on table passenger is 'Таблица пассажиров.';
comment on column passenger.id is 'Уникальный идентификатор пассажира.';
comment on column passenger.name is 'ФИО пассажира.';
comment on column passenger.email is 'Электронная почта пассажира.';
comment on column passenger.phone is 'Номер телефона пассажира.';
comment on column passenger.registered_at is 'Дата регистрации пассажира.';

